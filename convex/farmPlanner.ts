/** List tasks for a farmer (with optional status/season filters) */
export const listTasks = query({
  args: {
    farmerId: v.id("users"),
    status: v.optional(v.union(
      v.literal("upcoming"),
      v.literal("done"),
      v.literal("overdue"),
      v.literal("skipped")
    )),
    seasonPlanId: v.optional(v.id("farmSeasonPlans")),
  },
  handler: async (ctx, args) => {
    const now = Date.now();
    let rows: any[];
    if (args.seasonPlanId) {
      rows = await ctx.db
        .query("farmPlannerTasks")
        .withIndex("by_season_plan", (q: any) => q.eq("seasonPlanId", args.seasonPlanId))
        .collect();
    } else if (args.status) {
      rows = await ctx.db
        .query("farmPlannerTasks")
        .withIndex("by_farmer_status", (q: any) => q.eq("farmerId", args.farmerId).eq("status", args.status))
        .order("desc")
        .collect();
    } else {
      rows = await ctx.db
        .query("farmPlannerTasks")
        .withIndex("by_farmer", (q: any) => q.eq("farmerId", args.farmerId))
        .order("desc")
        .collect();
    }
    // Compute overdue: upcoming tasks past dueDate
    return rows.map((task) => ({
      ...task,
      isOverdue: task.status === "upcoming" && task.dueDate < now,
    }));
  },
});

