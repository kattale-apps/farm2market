/** Mark task done. If recurrence != "none", auto-creates next task. */
export const completeTask = mutation({
  args: {
    taskId: v.id("farmPlannerTasks"),
    requestingUserId: v.id("users"),
  },
  handler: async (ctx, args): Promise<void> => {
    const task = await ctx.db.get(args.taskId);
    if (!task) throw new Error("Task not found");
    if (task.farmerId !== args.requestingUserId) throw new Error("Not authorised");
    const now = getUgandaTime();
    await ctx.db.patch(args.taskId, { status: "done", completedAt: now, updatedAt: now });
    // Auto-generate next recurring task
    if (task.recurrence !== "none") {
      const offsets: Record<string, number> = { daily: 1, weekly: 7, monthly: 30 };
      const days = offsets[task.recurrence] ?? 7;
      const nextDueDate = task.dueDate + days * 24 * 60 * 60 * 1000;
      await ctx.db.insert("farmPlannerTasks", {
        farmerId: task.farmerId,
        seasonPlanId: task.seasonPlanId,
        taskName: task.taskName,
        emoji: task.emoji,
        category: task.category,
        dueDate: nextDueDate,
        status: "upcoming",
        recurrence: task.recurrence,
        linkedUnitId: task.linkedUnitId,
        notes: task.notes,
        isAutoGenerated: true,
        createdAt: now,
        updatedAt: now,
      });
    }
  },
});

