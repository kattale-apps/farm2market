/** Get calendar view: tasks grouped by date for a date range */
export const getCalendarTasks = query({
  args: {
    farmerId: v.id("users"),
    fromDate: v.number(), // timestamp start of range
    toDate: v.number(),   // timestamp end of range
  },
  handler: async (ctx, args): Promise<Record<string, any[]>> => {
    const tasks = await ctx.db
      .query("farmPlannerTasks")
      .withIndex("by_farmer", (q: any) => q.eq("farmerId", args.farmerId))
      .collect();
    const inRange = tasks.filter((t) => t.dueDate >= args.fromDate && t.dueDate <= args.toDate);
    const now = Date.now();
    const grouped: Record<string, any[]> = {};
    for (const task of inRange) {
      const date = new Date(task.dueDate);
      const key = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
      if (!grouped[key]) grouped[key] = [];
      grouped[key].push({ ...task, isOverdue: task.status === "upcoming" && task.dueDate < now });
    }
    return grouped;
  },
});
