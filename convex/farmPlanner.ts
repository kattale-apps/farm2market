import { getUgandaTime } from "./utils";

// ─── SEASON PLANS ────────────────────────────────────────────────────────────

/** List farmer's season plans */
export const listSeasonPlans = query({
  args: {
    farmerId: v.id("users"),
    status: v.optional(v.union(
      v.literal("planning"),
      v.literal("active"),
      v.literal("completed"),
      v.literal("abandoned")
    )),
  },
  handler: async (ctx, args) => {
    if (args.status) {
      return await ctx.db
        .query("farmSeasonPlans")
        .withIndex("by_farmer_status", (q: any) => q.eq("farmerId", args.farmerId).eq("status", args.status))
        .order("desc")
        .collect();
    }
    return await ctx.db
      .query("farmSeasonPlans")
      .withIndex("by_farmer", (q: any) => q.eq("farmerId", args.farmerId))
      .order("desc")
      .collect();
  },
});

/** Create a season plan. If linkedCostTemplateId provided, auto-generate tasks. */
export const createSeasonPlan = mutation({
  args: {
    farmerId: v.id("users"),
    planName: v.string(),
    category: v.union(v.literal("crop"), v.literal("livestock")),
    cropOrLivestockType: v.string(),
    emoji: v.optional(v.string()),
    startDate: v.number(),
    expectedHarvestDate: v.number(),
    acresCovered: v.optional(v.number()),
    linkedCostTemplateId: v.optional(v.id("cropCostTemplates")),
    linkedLivestockCostTemplateId: v.optional(v.id("livestockCostTemplates")),
    notes: v.optional(v.string()),
  },
  handler: async (ctx, args): Promise<Id<"farmSeasonPlans">> => {
    const now = getUgandaTime();
    const planId = await ctx.db.insert("farmSeasonPlans", {
      farmerId: args.farmerId,
      planName: args.planName,
      category: args.category,
      cropOrLivestockType: args.cropOrLivestockType,
      emoji: args.emoji,
      startDate: args.startDate,
      expectedHarvestDate: args.expectedHarvestDate,
      acresCovered: args.acresCovered,
      linkedCostTemplateId: args.linkedCostTemplateId,
      linkedLivestockCostTemplateId: args.linkedLivestockCostTemplateId,
      status: "planning",
      notes: args.notes,
      createdAt: now,
      updatedAt: now,
    });

    // Auto-generate tasks from linked cost template stages
    if (args.linkedCostTemplateId) {
      const template = await ctx.db.get(args.linkedCostTemplateId);
      if (template) {
        for (const stage of template.stages) {
          const dueDate = args.startDate + stage.weekFromStart * 7 * 24 * 60 * 60 * 1000;
          await ctx.db.insert("farmPlannerTasks", {
            farmerId: args.farmerId,
            seasonPlanId: planId,
            taskName: stage.stageName,
            emoji: stage.emoji,
            category: args.category,
            dueDate,
            status: "upcoming",
            recurrence: "none",
            isAutoGenerated: true,
            createdAt: now,
            updatedAt: now,
          });
        }
      }
    } else if (args.linkedLivestockCostTemplateId) {
      const template = await ctx.db.get(args.linkedLivestockCostTemplateId);
      if (template) {
        for (const stage of template.stages) {
          const dueDate = args.startDate + stage.weekFromStart * 7 * 24 * 60 * 60 * 1000;
          await ctx.db.insert("farmPlannerTasks", {
            farmerId: args.farmerId,
            seasonPlanId: planId,
            taskName: stage.stageName,
            emoji: stage.emoji,
            category: args.category,
            dueDate,
            status: "upcoming",
            recurrence: "none",
            isAutoGenerated: true,
            createdAt: now,
            updatedAt: now,
          });
        }
      }
    }

    return planId;
  },
});

/** Update season plan status */
export const updateSeasonPlanStatus = mutation({
  args: {
    planId: v.id("farmSeasonPlans"),
    requestingUserId: v.id("users"),
    status: v.union(
      v.literal("planning"),
      v.literal("active"),
      v.literal("completed"),
      v.literal("abandoned")
    ),
    notes: v.optional(v.string()),
  },
  handler: async (ctx, args): Promise<void> => {
    const plan = await ctx.db.get(args.planId);
    if (!plan) throw new Error("Plan not found");
    if (plan.farmerId !== args.requestingUserId) throw new Error("Not authorised");
    await ctx.db.patch(args.planId, { status: args.status, notes: args.notes, updatedAt: getUgandaTime() });
  },
});

/** Delete a season plan and its auto-generated tasks */
export const deleteSeasonPlan = mutation({
  args: {
    planId: v.id("farmSeasonPlans"),
    requestingUserId: v.id("users"),
  },
  handler: async (ctx, args): Promise<void> => {
    const plan = await ctx.db.get(args.planId);
    if (!plan) throw new Error("Plan not found");
    if (plan.farmerId !== args.requestingUserId) throw new Error("Not authorised");
    // Delete auto-generated tasks for this plan
    const tasks = await ctx.db
      .query("farmPlannerTasks")
      .withIndex("by_season_plan", (q: any) => q.eq("seasonPlanId", args.planId))
      .collect();
    for (const task of tasks.filter((t) => t.isAutoGenerated)) {
      await ctx.db.delete(task._id);
    }
    await ctx.db.delete(args.planId);
  },
});

